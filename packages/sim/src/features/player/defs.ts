import type { EntityDef } from '../../content/defs';
import type { SpriteDef } from '../../content/sprites';

/** Move intents shorter than this count as a stop: too small to move the body or to define a facing. */
export const MIN_MOVE_INTENT = 1e-3;

/**
 * Player feature owns def ids 1-99. Every id is an avatar: the look a player
 * gets when they join. The sim picks one through its rng (features/player/avatars.ts);
 * the client never chooses. Ids are forever: a new avatar takes the next
 * number, a retired one keeps its number out of use.
 */
export const PlayerDefId = {
  PlayerSky: 1,
  PlayerRose: 2,
  PlayerMoss: 3,
  PlayerSun: 4,
  PlayerPlum: 5,
  PlayerEmber: 6,
  PlayerTeal: 7,
  PlayerSlate: 8,
} as const;

/** How fast every avatar walks, in metres per second, and how big its body is, in metres. Avatars differ in looks only. */
const AVATAR_SPEED = 5;
const AVATAR_RADIUS = 0.4;

/**
 * Each avatar is a palette variant of the same placeholder character: the
 * sheet `sprites/<key>.png` holds four rows (down, up, left, right) of four
 * 16x24 frames, frame 0 of a row being the idle pose and the whole row the
 * walk cycle. The sheets are generated by packages/client/tools/generate-player-sheet.mjs,
 * whose palette table is keyed by the same sprite keys as below. `color` is
 * the shirt colour, for views that draw a flat shape instead of the sheet.
 */
const avatarLooks: readonly { readonly id: number; readonly name: string; readonly color: number }[] = [
  { id: PlayerDefId.PlayerSky, name: 'player-sky', color: 0x3b82f6 },
  { id: PlayerDefId.PlayerRose, name: 'player-rose', color: 0xe11d48 },
  { id: PlayerDefId.PlayerMoss, name: 'player-moss', color: 0x16a34a },
  { id: PlayerDefId.PlayerSun, name: 'player-sun', color: 0xf59e0b },
  { id: PlayerDefId.PlayerPlum, name: 'player-plum', color: 0x7c3aed },
  { id: PlayerDefId.PlayerEmber, name: 'player-ember', color: 0xea580c },
  { id: PlayerDefId.PlayerTeal, name: 'player-teal', color: 0x0d9488 },
  { id: PlayerDefId.PlayerSlate, name: 'player-slate', color: 0x475569 },
];

function avatarSprite(key: string): SpriteDef {
  return {
    key,
    frameWidth: 16,
    frameHeight: 24,
    pixelsPerMetre: 16,
    origin: { x: 0.5, y: 0.75 },
    frameRate: 8,
    directions: {
      down: { idle: 0, walk: { start: 0, end: 3 } },
      up: { idle: 4, walk: { start: 4, end: 7 } },
      left: { idle: 8, walk: { start: 8, end: 11 } },
      right: { idle: 12, walk: { start: 12, end: 15 } },
    },
  };
}

export const playerDefs: readonly EntityDef[] = avatarLooks.map(({ id, name, color }) => ({
  id,
  name,
  shape: 'circle',
  radius: AVATAR_RADIUS,
  speed: AVATAR_SPEED,
  color,
  sprite: avatarSprite(name),
}));

/** Every avatar a join may hand out, in id order. */
export const avatarDefIds: readonly number[] = playerDefs.map((def) => def.id);

const avatarDefIdSet: ReadonlySet<number> = new Set(avatarDefIds);

/** True when `defId` is one of the player avatars, so an entity wearing it is a player. */
export function isAvatarDefId(defId: number): boolean {
  return avatarDefIdSet.has(defId);
}
