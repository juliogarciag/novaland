/**
 * The text of the TypeScript module a region is committed as: its rows, its
 * legend, where it sits on the Earth and what it was made from.
 */

/**
 * `rows` are the tile rows, one character per tile. `kinds` are the entries
 * of `TILE_KINDS` the rows use; the legend lists exactly those. `spawn` is a
 * tile. `grid` is what `gridOfRegion` returned and `sources` the datasets,
 * each with `name`, `licence` and `credit`.
 */
export function regionModuleText({ name, grid, rows, spawn, kinds, sources }) {
  const legend = kinds.map((kind) => `${JSON.stringify(kind.character)}: TerrainDefId.${kind.defName}`).join(', ');
  return `// Generated by \`pnpm region:build ${name}\` (scripts/region). Do not edit by hand: change the script or the region's file there and run it again.
//
// Made from:
${sources.map((source) => `// - ${source.name}. ${source.licence}. ${source.credit}.`).join('\n')}
import { TerrainDefId } from '../../../features/terrain/defs';
import type { Region } from './types';

export const ${name}: Region = {
  name: ${JSON.stringify(name)},
  grid: { north: ${grid.north}, west: ${grid.west}, degreesPerColumn: ${grid.degreesPerColumn}, degreesPerRow: ${grid.degreesPerRow}, standardParallel: ${grid.standardParallel}, kilometresPerTile: ${grid.kilometresPerTile} },
  sources: [
${sources.map((source) => `    { name: ${JSON.stringify(source.name)}, licence: ${JSON.stringify(source.licence)}, credit: ${JSON.stringify(source.credit)} },`).join('\n')}
  ],
  map: {
    spawn: { column: ${spawn.column}, row: ${spawn.row} },
    areas: [
      {
        name: ${JSON.stringify(name)},
        origin: { column: 0, row: 0 },
        legend: { ${legend} },
        // prettier-ignore
        rows: [
${rows.map((row) => `          ${JSON.stringify(row)},`).join('\n')}
        ],
      },
    ],
  },
};
`;
}
